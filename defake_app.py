class ImprovedResNet(nn.Module):
    """Binary classification model (Real vs Fake)"""
    def __init__(self, num_classes=2, dropout_rate=0.5):
        super(ImprovedResNet, self).__init__()

        # Rectified: Replaced deprecated 'pretrained=False' with 'weights=None'
        self.resnet = models.resnet18(weights=None)

        # Freeze all parameters except the last 10
        for param in list(self.resnet.parameters())[:-10]:
            param.requires_grad = False

        num_features = self.resnet.fc.in_features
        self.resnet.fc = nn.Sequential(
            nn.Dropout(dropout_rate),
            nn.Linear(num_features, 256),
            nn.ReLU(),
            nn.Dropout(dropout_rate/2),
            nn.Linear(256, num_classes)
        )

        # Initialize weights for the new fully connected layer
        for m in self.resnet.fc.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_uniform_(m.weight)
                nn.init.constant_(m.bias, 0)

    def forward(self, x):
        return self.resnet(x)


class DualEfficientNetB0(nn.Module):
    """Attribution model - Dual-branch architecture: RGB + FFT frequency domain"""
    def __init__(self, num_classes=3, pretrained=False, dropout=0.3):
        super().__init__()

        # Rectified: Replaced deprecated 'pretrained=...' with modern 'weights=...' API
        rgb_weights = models.EfficientNet_B0_Weights.DEFAULT if pretrained else None
        rgb_model = models.efficientnet_b0(weights=rgb_weights)

        self.rgb_backbone = nn.Sequential(
            rgb_model.features,
            nn.AdaptiveAvgPool2d(1),
            nn.Flatten()
        )

        # Rectified: Replaced deprecated 'pretrained=...' with modern 'weights=...' API
        fft_weights = models.EfficientNet_B0_Weights.DEFAULT if pretrained else None
        fft_model = models.efficientnet_b0(weights=fft_weights)

        self.fft_backbone = nn.Sequential(
            fft_model.features,
            nn.AdaptiveAvgPool2d(1),
            nn.Flatten()
        )

        feat_dim = 1280  # EfficientNet-B0 feature dimension
        self.classifier = nn.Sequential(
            nn.Dropout(dropout),
            nn.Linear(feat_dim * 2, 512),
            nn.ReLU(inplace=True),
            nn.Dropout(dropout),
            nn.Linear(512, num_classes)
        )

    def forward(self, rgb, fft):
        rgb_feat = self.rgb_backbone(rgb)
        fft_feat = self.fft_backbone(fft)
        combined = torch.cat([rgb_feat, fft_feat], dim=1)
        out = self.classifier(combined)
        return out


