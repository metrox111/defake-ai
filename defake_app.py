class GradCAM:
    """Gradient-weighted Class Activation Mapping for model interpretability"""
    def __init__(self, model, target_layer, is_dual_input=False):
        self.model = model
        self.target_layer = target_layer
        self.is_dual_input = is_dual_input
        self.gradients = None
        self.activations = None
        self.hook_layers()

    def hook_layers(self):
        def forward_hook(module, input, output):
            self.activations = output.detach()

        def backward_hook(module, grad_input, grad_output):
            self.gradients = grad_output[0].detach()

        self.target_layer.register_forward_hook(forward_hook)
        self.target_layer.register_full_backward_hook(backward_hook)

    def generate_cam(self, input_tensor, target_class=None, fft_tensor=None):
        self.model.eval()

        # Handle dual-input models (attribution model needs both RGB and FFT)
        if self.is_dual_input and fft_tensor is not None:
            output = self.model(input_tensor, fft_tensor)
        else:
            output = self.model(input_tensor)

        if target_class is None:
            target_class = output.argmax(dim=1).item()

        self.model.zero_grad()
        output[0, target_class].backward()

        # Check if gradients were captured
        if self.gradients is None:
            raise RuntimeError("Gradients were not captured. Check hook logic or target layer.")

        # Pool gradients across channels
        weights = self.gradients.mean(dim=(2, 3), keepdim=True)
        # Weight the feature maps
        cam = (weights * self.activations).sum(dim=1, keepdim=True)
        # Apply ReLU
        cam = F.relu(cam)
        # Resize to original image size
        cam = F.interpolate(cam, size=input_tensor.shape[2:], mode='bilinear', align_corners=False)
        cam = cam.squeeze().cpu().numpy()

        # Normalize the CAM
        cam_min = cam.min()
        cam_max = cam.max()
        cam = (cam - cam_min) / (cam_max - cam_min + 1e-8)

        return cam, target_class


