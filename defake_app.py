def create_gradio_interface(binary_model_path: str, attribution_model_path: str):
    """Create and launch Gradio interface"""

    # Initialize the pipeline
    try:
        pipeline = DeFakePipeline(binary_model_path, attribution_model_path)
    except Exception as e:
        print(f"Failed to initialize pipeline: {e}")
        # Create a dummy interface to show the error
