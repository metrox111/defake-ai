class DeFakePipeline:
    """Main pipeline for deepfake detection and attribution"""

    def __init__(self, binary_model_path: str, attribution_model_path: str, device: str = 'cuda'):
        self.device = torch.device(device if torch.cuda.is_available() else 'cpu')
        print(f"Using device: {self.device}")

        try:
            # Load binary model
            self.binary_model = ImprovedResNet(num_classes=2, dropout_rate=0.5)
            self.binary_model.load_state_dict(torch.load(binary_model_path, map_location=self.device))
            self.binary_model.to(self.device)
            self.binary_model.eval()
            print("Binary model loaded successfully.")

            # Load attribution model
            self.attribution_model = DualEfficientNetB0(num_classes=3, pretrained=False, dropout=0.3)
            # Load only the model_state_dict from the checkpoint
            attribution_state = torch.load(attribution_model_path, map_location=self.device)

            # Check if the loaded object is a dictionary and has 'model_state_dict'
            if isinstance(attribution_state, dict) and 'model_state_dict' in attribution_state:
                self.attribution_model.load_state_dict(attribution_state['model_state_dict'])
                print("Attribution model checkpoint loaded successfully.")
            else:
                # Assume it's just the state_dict
                self.attribution_model.load_state_dict(attribution_state)
                print("Attribution model state_dict loaded successfully.")

            self.attribution_model.to(self.device)
            self.attribution_model.eval()

        except FileNotFoundError as e:
            print(f"FATAL ERROR: Model file not found. {e}")
            raise
        except Exception as e:
            print(f"FATAL ERROR: Error loading models. {e}")
            raise

        # Initialize Grad-CAM
        self.binary_gradcam = GradCAM(self.binary_model, self.binary_model.resnet.layer4[-1], is_dual_input=False)
        # Target the last conv block of the EfficientNet features
        self.attribution_gradcam = GradCAM(self.attribution_model, self.attribution_model.rgb_backbone[0][-1], is_dual_input=True)

        # CHANGED: Reversed label order - Fake is now index 0, Real is index 1
        self.binary_classes = ['Fake', 'Real']
        self.gan_classes = ['StyleGAN1', 'StyleGAN2', 'StyleGAN3']
        print("DeFakePipeline initialized.")

    def predict(self, image: Image.Image) -> Dict:
        """Run complete detection pipeline with conditional attribution"""
        if image is None:
            return {
                'error': 'No image provided',
                'binary_result': None,
                'attribution_result': None
            }

        # Prepare image
        img_array = np.array(image.resize((224, 224)))
        img_tensor = preprocess_image(image).to(self.device)

        # ========================================================================
        # STAGE 1: BINARY CLASSIFICATION (Real vs Fake)
        # ========================================================================
        with torch.no_grad():
            binary_output = self.binary_model(img_tensor)
            binary_probs = F.softmax(binary_output, dim=1)[0]
            binary_pred = binary_probs.argmax().item()
            binary_conf = binary_probs[binary_pred].item()

        # --- RECTIFIED: Added error handling for Grad-CAM ---
        try:
            # Generate Grad-CAM for binary model (requires gradients)
            img_tensor_grad = img_tensor.clone().requires_grad_(True)
            binary_cam, _ = self.binary_gradcam.generate_cam(img_tensor_grad, target_class=binary_pred)
            binary_overlay = overlay_heatmap(img_array, binary_cam, alpha=0.4)
        except Exception as e:
            print(f"Error generating binary Grad-CAM: {e}")
            binary_overlay = img_array # Show original image on failure
        # --- End of fix ---

        result = {
            'binary_prediction': self.binary_classes[binary_pred],
            'binary_confidence': f"{binary_conf * 100:.2f}%",
            'binary_probs': {
                'Fake': f"{binary_probs[0].item() * 100:.2f}%",
                'Real': f"{binary_probs[1].item() * 100:.2f}%"
            },
            'binary_heatmap': binary_overlay,
            # CHANGED: Now checking if index 0 (Fake) instead of index 1
            'is_fake': binary_pred == 0
        }

        # ========================================================================
        # STAGE 2: ATTRIBUTION (Only executed if image is classified as FAKE)
        # ========================================================================
        # CHANGED: Now checking if index 0 (Fake) instead of index 1
        if binary_pred == 0:  # FAKE detected
            # Prepare FFT frequency domain representation
            fft_tensor = get_fft_spectrum(img_tensor).unsqueeze(0).to(self.device)

            # Run attribution model
            with torch.no_grad():
                attribution_output = self.attribution_model(img_tensor, fft_tensor)
                attribution_probs = F.softmax(attribution_output, dim=1)[0]
                gan_pred = attribution_probs.argmax().item()
                gan_conf = attribution_probs[gan_pred].item()

            # --- RECTIFIED: Added error handling for Grad-CAM ---
            try:
                # Generate Grad-CAM for attribution model (requires gradients)
                img_tensor_grad = img_tensor.clone().requires_grad_(True)
                fft_tensor_grad = fft_tensor.clone().requires_grad_(True)
                attr_cam, _ = self.attribution_gradcam.generate_cam(
                    img_tensor_grad,
                    target_class=gan_pred,
                    fft_tensor=fft_tensor_grad
                )
                attr_overlay = overlay_heatmap(img_array, attr_cam, alpha=0.4)
            except Exception as e:
                print(f"Error generating attribution Grad-CAM: {e}")
                attr_overlay = img_array # Show original image on failure
            # --- End of fix ---

            result['gan_type'] = self.gan_classes[gan_pred]
            result['gan_confidence'] = f"{gan_conf * 100:.2f}%"
            result['gan_probs'] = {
                'StyleGAN1': f"{attribution_probs[0].item() * 100:.2f}%",
                'StyleGAN2': f"{attribution_probs[1].item() * 100:.2f}%",
                'StyleGAN3': f"{attribution_probs[2].item() * 100:.2f}%"
            }
            result['attribution_heatmap'] = attr_overlay
            result['attribution_performed'] = True
        else:  # REAL detected - skip attribution
            result['gan_type'] = None
            result['gan_confidence'] = None
            result['gan_probs'] = None
            result['attribution_heatmap'] = None
            result['attribution_performed'] = False

        return result


