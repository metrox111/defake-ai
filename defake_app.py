def get_fft_spectrum(image_tensor: torch.Tensor) -> torch.Tensor:
    """Convert image to FFT frequency domain representation"""
    # Squeeze batch dimension and convert to numpy
    img_np = image_tensor.squeeze(0).cpu().numpy()

    # Transpose from (C, H, W) to (H, W, C)
    if img_np.shape[0] == 3:
        img_np = np.transpose(img_np, (1, 2, 0))

    # Denormalize (assuming standard ImageNet stats)
    mean = np.array([0.485, 0.456, 0.406])
    std = np.array([0.229, 0.224, 0.225])
    img_np = (img_np * std + mean) * 255.0
    img_np = np.clip(img_np, 0, 255).astype(np.uint8)

    # Convert to grayscale
    gray = cv2.cvtColor(img_np, cv2.COLOR_RGB2GRAY)

    # Perform FFT
    fft = np.fft.fft2(gray)
    fft_shift = np.fft.fftshift(fft)
    magnitude = np.log(np.abs(fft_shift) + 1)

    # Normalize magnitude map to [0, 1]
    mag_min = magnitude.min()
    mag_max = magnitude.max()
    magnitude = (magnitude - mag_min) / (mag_max - mag_min + 1e-8)

    # Stack to 3 channels to match model input
    fft_rgb = np.stack([magnitude] * 3, axis=0)

    tensor = torch.from_numpy(fft_rgb).float()

    # --- RECTIFIED: Added normalization ---
    # The EfficientNet backbone expects inputs normalized with ImageNet stats.
    # The FFT image should be normalized just like the RGB image.
    normalize = transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
    return normalize(tensor)
    # --- End of fix ---


def preprocess_image(image: Image.Image, size: int = 224) -> torch.Tensor:
    """Standard preprocessing for RGB images"""
    transform = transforms.Compose([
        transforms.Resize((size, size)),
        transforms.ToTensor(),
        transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
    ])
    return transform(image).unsqueeze(0)


def overlay_heatmap(image: np.ndarray, heatmap: np.ndarray, alpha: float = 0.5) -> np.ndarray:
    """Overlay Grad-CAM heatmap on original image"""
    heatmap_colored = cv2.applyColorMap((heatmap * 255).astype(np.uint8), cv2.COLORMAP_JET)
    heatmap_colored = cv2.cvtColor(heatmap_colored, cv2.COLOR_BGR2RGB)

    # Ensure image is in 0-255 range, uint8
    if image.max() <= 1.0:
        image = (image * 255).astype(np.uint8)
    if image.dtype != np.uint8:
         image = image.astype(np.uint8)

    overlay = cv2.addWeighted(image, 1 - alpha, heatmap_colored, alpha, 0)
    return overlay


